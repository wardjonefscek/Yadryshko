//! Единая политика допусков.
//!
//! Правило: величины в миллиметрах, если в имени не сказано иное.
//! Точные решения (предикаты) допусками не пользуются вовсе: допуски нужны
//! только там, где результат строится приближённо.

/// Шаг 2D-сетки, мм: 1 мкм.
pub const GRID_STEP_MM: f64 = 0.001;

/// Число шагов 2D-сетки в одном миллиметре.
pub const GRID_PER_MM: f64 = 1000.0;

/// Предел координаты 2D-сетки по модулю: 2^40 мкм ≈ 1100 км.
///
/// РИСК: на этом пределе держится точность 2D-предикатов в `i128`.
/// Разности координат не больше 2^41, произведения — 2^82, и даже
/// выражения третьей степени (до 2^123) не переполняют `i128`.
/// Поднимать предел можно только вместе с пересчётом этих оценок.
pub const GRID_LIMIT: i64 = 1 << 40;

/// Линейный допуск для приближённых построений в 3D, мм.
/// Понадобится со ступени 4; сейчас — только в проверках.
pub const LINEAR_TOL_MM: f64 = 1e-6;

/// Допуск хорды по умолчанию, мм: на сколько ломаная может отойти от дуги
/// (стрелка прогиба хорды). 2 мкм — заметно точнее печати и фрезы.
pub const CHORD_TOL_MM: f64 = 0.002;

/// Меньше этого допуск хорды не берётся: точнее не позволит сама сетка.
pub const MIN_CHORD_TOL_MM: f64 = 0.0005;

/// Больше стольких хорд на одну дугу не строится — защита от огромных радиусов
/// при крошечном допуске (тогда допуск не выдерживается).
pub const MAX_ARC_CHORDS: usize = 1 << 20;

/// Допуск восстановления дуг по умолчанию, мм: на сколько подогнанный контур
/// (отрезки и дуги) может отойти от ломаной. 5 мкм — ниже точности фрезы и печати.
pub const FIT_TOL_MM: f64 = 0.005;
